public class Calculator {
    public static int add(int one, int two)
    {
        return one + two;
    }
    public static int sub(int one, int two)
    {
        return one - two;
    }
    public static int mult(int one, int two)
    {
        return one * two;
    }
    public static double div(int one, int two)
    {
        return one/(double)two;
    }
    public static int square(int one)
    {
        return one * one;
    }
}
